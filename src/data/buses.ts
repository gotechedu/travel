import { Bus, BusSeat } from '../types';

const generateSeats = (basePrice: number): BusSeat[] => {
  const seats: BusSeat[] = [];
  // Lower deck: 15 seats (Seater 2+1 layout)
  for (let r = 1; r <= 5; r++) {
    seats.push({
      id: `L${r}A`,
      number: `L${r}A`,
      deck: 'lower',
      type: 'seater',
      isAvailable: !(r === 2 || r === 4),
      price: basePrice,
      isLadiesOnly: r === 1,
      row: r,
      col: 1,
    });
    seats.push({
      id: `L${r}B`,
      number: `L${r}B`,
      deck: 'lower',
      type: 'seater',
      isAvailable: r !== 3,
      price: basePrice,
      row: r,
      col: 2,
    });
    seats.push({
      id: `L${r}C`,
      number: `L${r}C`,
      deck: 'lower',
      type: 'seater',
      isAvailable: true,
      price: basePrice,
      row: r,
      col: 4, // Aisle in col 3
    });
  }

  // Upper deck: 10 sleeper berths (2+1 layout)
  for (let r = 1; r <= 5; r++) {
    seats.push({
      id: `U${r}A`,
      number: `U${r}A`,
      deck: 'upper',
      type: 'sleeper',
      isAvailable: r !== 1,
      price: basePrice + 350,
      row: r,
      col: 1,
    });
    seats.push({
      id: `U${r}B`,
      number: `U${r}B`,
      deck: 'upper',
      type: 'sleeper',
      isAvailable: true,
      price: basePrice + 350,
      row: r,
      col: 2,
    });
    seats.push({
      id: `U${r}C`,
      number: `U${r}C`,
      deck: 'upper',
      type: 'sleeper',
      isAvailable: r !== 5,
      price: basePrice + 350,
      row: r,
      col: 4,
    });
  }

  return seats;
};

